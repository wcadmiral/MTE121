#include <iostream>

/*
In for loop: int i=1 -> initializes variable 
i<=3 -> repeats until condition is broken
i++ updates condition
*/
int main(){
    /*
    In for loop: int i=1 -> initializes variable 
    i<=3 -> repeats until condition is broken
    i++ updates condition
    */
    for (int i=1 ; i<=3; i++) { //runs code 3 times in this case, three parts are initialization, condition, and update
        std::cout <<i<<std::endl; //counts from 1 to 3
    }

    

}